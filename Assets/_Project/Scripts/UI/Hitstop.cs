using UnityEngine;

namespace Game.UI
{
    /// <summary>
    /// Короткая остановка времени на крупном слиянии: партия замирает на несколько кадров, и ход
    /// читается как удар, а не как перекладывание иконок. Проба стадии M30 — решение человека
    /// 08.09.2026: приём сильный, но он тормозит и добычу, и контракты, и утечку накала, то есть
    /// стоит игроку долей секунды его же темпа. Оставлять или снимать — по итогу плейтеста.
    ///
    /// Бот этого не видит: `BalanceBot` играет без сцены и тикает своим шагом, а не `Time`.
    /// Значит, ни одно число баланса и ни один потолок кампании от `Hitstop` не меняются —
    /// расходится только живая партия, и ровно на то время, пока идёт остановка.
    ///
    /// `timeScale` в проекте больше никто не трогает (пауза останавливает партию сама, не
    /// временем), поэтому возврат к единице безусловный: делить этот рычаг не с кем.
    /// </summary>
    public sealed class Hitstop : MonoBehaviour
    {
        [Tooltip("До какой доли замедляется время на пике. Ноль был бы полной заморозкой — она читается как зависание")]
        [SerializeField, Range(0.02f, 1f)] float scale = 0.12f;

        [Tooltip("Сколько длится остановка. Дольше 0.1 с игрок читает как лаг, а не как удар")]
        [SerializeField] float seconds = 0.07f;

        float left;

        /// <summary>Ударить. Повторный вызов продлевает остановку с начала, а не складывается.</summary>
        public void Play()
        {
            left = seconds;
            Time.timeScale = scale;
        }

        void Update()
        {
            if (left <= 0f)
                return;

            left -= Time.unscaledDeltaTime;
            if (left <= 0f)
                Time.timeScale = 1f;
        }

        /// <summary>
        /// Сцена перезагружается кнопкой рестарта (M19), и уйти из неё с замедленным временем
        /// нельзя: `timeScale` живёт дольше объекта.
        /// </summary>
        void OnDisable() => Time.timeScale = 1f;
    }
}
