namespace Game.Tutorial
{
    /// <summary>
    /// Шаги обучения по порядку. Урок про кнопку «Продать всё» стоит **после моста**, а не до
    /// него: до моста склад пуст — сценарий сам тратит стартовые доски на контракт и щебень на
    /// две дороги, — и продавать кнопке нечего, а приходит она только с запасом сверх резерва.
    /// Открытое гряду поле кормит склад сразу с нескольких месторождений, и там кнопка наконец
    /// значит то, чему учит. Накал едет следом за ней: волна продажи и выносит его к потолку.
    ///
    /// Каждый шаг закрывается одним игровым событием, кроме последнего:
    /// премию за чистый склад подсказкой не подвести — она требует двадцати действий подряд, —
    /// поэтому шаг её называет и гаснет сам.
    /// </summary>
    public enum TutorialStep
    {
        OpenStone,
        BuildRoad,
        WatchDelivery,
        Merge,
        Convert,
        Goal,
        Contract,
        CraftBoard,
        Wall,
        Bridge,
        SellButton,
        Heat,
        Sweep,
        Done
    }
}
