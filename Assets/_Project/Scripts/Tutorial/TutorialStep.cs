namespace Game.Tutorial
{
    /// <summary>
    /// Шаги обучения по порядку. Каждый закрывается **одним** разрешённым действием, а шаг,
    /// которому делать нечего, — кнопкой «Дальше» на самой карточке. Третьего не бывает:
    /// эмерджентных условий вроде «следующего слияния» или «утечки накала» в сценарии больше
    /// нет — на них обучение и залипало между действиями (решение человека 11.09.2026).
    ///
    /// Карта первого уровня рукотворная (<see cref="Grid.TutorialMap"/>), поэтому у каждого
    /// шага цель одна и известна заранее, а всё остальное поле и склад на это время закрыты.
    /// </summary>
    public enum TutorialStep
    {
        OpenStone,
        BuildRoad,
        WatchDelivery,
        Merge,
        Convert,
        Goal,
        Contract,
        OpenWood,
        CraftBoard,
        Wall,
        Bypass,
        Bridge,
        SellButton,
        Heat,
        Sweep,
        Done
    }
}
